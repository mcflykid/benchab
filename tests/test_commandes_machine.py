"""Les commandes exécutées sont confrontées au mode et à ses limites, pas au seul nom du profil."""

from benchab.controles.commandes_machine import analyser, verifier_format_s1
from benchab.machine.configuration import charger


def _settings():
    champs = {
        "printer_settings_id": "Anycubic Kobra S1 0.4 nozzle",
        "filament_settings_id": ["PLA"],
        "curr_bed_type": "Textured PEI Plate",
        "nozzle_temperature_initial_layer": ["210"],
        "textured_plate_temp_initial_layer": ["55"],
    }
    for axe in "xyze":
        champs["machine_max_speed_" + axe] = ["15", "7.5", "19.5"] if axe == "z" else ["600", "300", "780"]
        champs["machine_max_acceleration_" + axe] = ["1000"] * 3 if axe == "z" else ["20000"] * 3
        champs["machine_max_jerk_" + axe] = ["15"] * 3
    for c in ["extruding", "retracting", "travel"]:
        champs["machine_max_acceleration_" + c] = ["20000"] * 3
    return champs


def _code(x="600", temp="210"):
    return (
        "M201 X20000 Y20000 Z1000 E20000\n"
        f"M203 X{x} Y600 Z15 E600\nM204 P20000 R20000 T20000\n"
        "M205 X15 Y15 Z15 E15\n"
        f"G9111 bedTemp=55 extruderTemp={temp}\n;LAYER_CHANGE\nM204 P500"
    )


def test_m203_780_au_lieu_de_600_fail():
    """Reproduit M203 X780/600 mm/s ; attend FAIL, n'abaisse pas la limite ni ne corrige le G-code."""
    rapport = analyser(_code("780"), _settings(), charger()["mouvement"])
    assert rapport["statut"] == "FAIL"
    assert any(
        r.get("commande") == "M203" and r.get("parametre") == "X" and r["statut"] == "FAIL"
        for r in rapport["resultats"]
    )


def test_m203_780_reste_fail_avec_vecteur_court_et_limite_repliee():
    """M203 X780 reste FAIL face à600 mm/s ; la lecture courte ne permet aucune écriture ni hausse de limite."""
    cfg = _settings()
    cfg["machine_max_speed_x"] = ["600"]
    rapport = analyser(_code("780"), cfg, charger()["mouvement"])
    assert rapport["statut"] == "FAIL"
    ligne = next(
        r for r in rapport["resultats"]
        if r.get("commande") == "M203" and r.get("parametre") == "X"
    )
    assert ligne["attendu_3mf"] == 600.0
    assert ligne["statut"] == "FAIL"


def test_demarrage_conforme_et_temperature_erronee():
    """Valide vitesses/accélérations/jerk et 210/55 °C ; une chauffe différente échoue, sans modification."""
    assert analyser(_code(), _settings(), charger()["mouvement"])["statut"] == "PASS"
    assert analyser(_code(temp="220"), _settings(), charger()["mouvement"])["statut"] == "FAIL"


def test_temperature_second_outil_absente_reste_non_verifiee():
    """Ne replie pas une température d'outil manquante sur le filament zéro ; aucune correspondance inventée."""
    cfg = _settings()
    cfg["filament_settings_id"] = ["PLA", "PETG"]
    texte = "T1\n" + _code()
    rapport = analyser(texte, cfg, charger()["mouvement"])
    assert rapport["statut"] == "NON VÉRIFIÉ"
    ligne = next(
        r for r in rapport["resultats"]
        if r.get("commande") == "G9111" and r.get("parametre") == "extruderTemp"
    )
    assert ligne["attendu_3mf"] is None and ligne["statut"] == "NON VÉRIFIÉ"


def test_valeur_attendue_absente_jamais_pass():
    """Retire la source d'une limite ; attend NON VÉRIFIÉ, aucune valeur par défaut inventée."""
    cfg = _settings()
    del cfg["machine_max_speed_x"]
    rapport = analyser(_code(), cfg, charger()["mouvement"])
    assert rapport["statut"] == "NON VÉRIFIÉ"


def test_m204_vide_et_plateau_inconnu_non_verifies():
    """Commandes sans paramètres et plateau inconnu restent NON VÉRIFIÉ, sans choix de température implicite."""
    assert (
        analyser(_code().replace("M204 P20000 R20000 T20000", "M204"), _settings(), charger()["mouvement"])["statut"]
        == "NON VÉRIFIÉ"
    )
    cfg = _settings()
    del cfg["curr_bed_type"]
    assert analyser(_code(), cfg, charger()["mouvement"])["statut"] == "NON VÉRIFIÉ"


def test_format_s1_qualifie_et_controle_avant_premiere_couche():
    """Structure ASN 2.0.0.3 exacte : une commande en corps de pièce ne remplace pas le démarrage."""
    entete = (
        "; HEADER_BLOCK_START\n; generated by AnycubicSlicerNext 2.0.0.3 on 2026-11-06 at 09:56:56\n"
        "; HEADER_BLOCK_END\n"
    )
    modele = {"printer_model": "Anycubic Kobra S1"}
    texte = entete + _code()
    assert verifier_format_s1(texte, modele, "asn-s1-2.0.0.3")["statut"] == "PASS"
    manque = texte.replace("M203 X600 Y600 Z15 E600\n", "") + "\nM203 X600 Y600 Z15 E600\n"
    rapport = verifier_format_s1(manque, modele, "asn-s1-2.0.0.3")
    assert rapport["statut"] == "FAIL" and "M203" in rapport["detail"]
    incomplet = texte.replace("; HEADER_BLOCK_END\n", "")
    assert verifier_format_s1(incomplet, modele, "asn-s1-2.0.0.3")["statut"] == "FAIL"
    inconnu = texte.replace("2.0.0.3", "2.0.0.4")
    assert verifier_format_s1(inconnu, modele, "asn-s1-2.0.0.3")["statut"] == "NON VÉRIFIÉ"
    assert verifier_format_s1(texte, {}, "asn-s1-2.0.0.3")["statut"] == "NON VÉRIFIÉ"
    assert verifier_format_s1(texte, modele, None)["statut"] == "NON VÉRIFIÉ"
