"""Comparaison des reçus et dépôts archivés, sans lancement du moteur."""
import hashlib
import json
from zipfile import ZipFile

import pytest

from benchab.controles.rejeux_gcode import comparer

SOURCE = "a" * 64
ENTREE = "b" * 64
GCODE = b"G90\nM83\nG1 X0 Y0 Z0.2\n;TYPE:Support\nG1 X1 Y0 E1\n"


def _recu(prive, nom, gcode, *, jour=11, source=SOURCE, entree=ENTREE, plaque_double=False):
    """Écrit un reçu et un 3MF synthétiques dans un atelier temporaire."""
    sortie = prive / (nom + ".3mf")
    with ZipFile(sortie, "w") as archive:
        entete = f"; generated by AnycubicSlicerNext 2.0.0.3 on 2026-11-{jour:02d} at 12:00:00\n".encode()
        archive.writestr("Metadata/plate_1.gcode", entete + gcode)
        if plaque_double:
            archive.writestr("Metadata/plate_01.gcode", entete + gcode)
    recu = prive / (nom + ".json")
    recu.write_text(json.dumps({
        "code": 0, "code_processus": 0, "validation_sortie": {"statut": "PASS"},
        "publication_sortie": {"statut": "PASS", "chemin": str(sortie)},
        "destination_finale": str(sortie),
        "source_sha256": source, "entree_sha256": entree,
        "sortie_sha256": hashlib.sha256(sortie.read_bytes()).hexdigest(),
        "plan_matrices_origine": {"binaire": None},
    }))
    return recu


def test_date_seule_n_est_pas_une_divergence_de_trajet(tmp_path):
    """Distingue les octets, la date, les trajets et la preuve d’identité du moteur."""
    a = _recu(tmp_path, "a", GCODE)
    b = _recu(tmp_path, "b", GCODE, jour=12)
    r = comparer(tmp_path, (a, b), plaque=1)
    assert r["statut"] == "PASS"
    assert r["gcode_brut_identique"] is False
    assert r["gcode_hors_date_identique"] is True
    assert r["depots_supports_identiques"] is True
    assert r["mesures_supports_identiques"] is True
    assert r["identite_binaire"]["statut"] == "NON VÉRIFIÉ"
    assert r["validation_physique"] is False


def test_trajets_differents_avec_mesures_agregees_egales(tmp_path):
    """Un millimètre de trajet identique en longueur ne prouve pas une position identique."""
    a = _recu(tmp_path, "a", GCODE)
    b = _recu(tmp_path, "b", GCODE.replace(b"X1 Y0", b"X0 Y1"))
    r = comparer(tmp_path, (a, b), plaque=1)
    assert r["statut"] == "WARN"
    assert r["gcode_hors_date_identique"] is False and r["depots_supports_identiques"] is False
    assert r["mesures_supports_identiques"] is True
    assert r["rejeux"][0]["supports"]["support"] == {"segments": 1, "longueur_mm": 1.0}


@pytest.mark.parametrize("motif", ["entree", "source", "sortie", "plaque", "couverture"])
def test_rejeu_non_qualifie_sans_verdict_d_egalite(tmp_path, motif):
    """Une provenance non appariée ou une mesure incomplète bloque la comparaison."""
    a = _recu(tmp_path, "a", GCODE)
    b = _recu(
        tmp_path, "b", GCODE if motif != "couverture" else b"G90\n",
        entree="c" * 64 if motif == "entree" else ENTREE,
        source="d" * 64 if motif == "source" else SOURCE,
        plaque_double=motif == "plaque",
    )
    if motif == "sortie":
        (tmp_path / "b.3mf").write_bytes((tmp_path / "a.3mf").read_bytes() + b"change")
    r = comparer(tmp_path, (a, b), plaque=1)
    assert r["statut"] == "NON VÉRIFIÉ"
    assert r["depots_supports_identiques"] is None
    assert r["raison"]


def test_cli_compare_sans_base_et_conserve_le_warn(tmp_path, monkeypatch, capsys):
    """Le code 1 est conservé et le rapport complet paraît uniquement sur demande."""
    from benchab import cli

    a = _recu(tmp_path, "a", GCODE)
    b = _recu(tmp_path, "b", GCODE.replace(b"X1 Y0", b"X0 Y1"))
    sortie = tmp_path / "comparaison.json"
    monkeypatch.setattr(cli, "Base", lambda *_a, **_k: pytest.fail("La base ne doit pas être ouverte"))
    commande = ["--prive", str(tmp_path), "controle", "rejeux-gcode", str(a), str(b), "--plaque", "1"]
    assert cli.main([*commande, "--sortie", str(sortie)]) == 1
    assert json.loads(capsys.readouterr().out) == json.loads(sortie.read_bytes())
    avant = sortie.read_bytes()
    assert cli.main([*commande, "--sortie", str(sortie)]) == 2
    assert sortie.read_bytes() == avant
    assert not (tmp_path / "benchab.sqlite").exists()


def test_commentaire_deja_normalise_ne_masque_pas_un_ecart(tmp_path):
    """Un commentaire littéral ne peut pas se confondre avec une date exclue."""
    a = _recu(tmp_path, "a", GCODE)
    b = _recu(tmp_path, "b", GCODE)
    sortie = tmp_path / "b.3mf"
    with ZipFile(sortie, "w") as archive:
        archive.writestr("Metadata/plate_1.gcode", b"; generated by AnycubicSlicerNext 2.0.0.3 on <date>\n" + GCODE)
    recu = json.loads(b.read_bytes())
    recu["sortie_sha256"] = hashlib.sha256(sortie.read_bytes()).hexdigest()
    b.write_text(json.dumps(recu))
    resultat = comparer(tmp_path, (a, b), plaque=1)
    assert resultat["statut"] == "WARN"
    assert resultat["gcode_hors_date_identique"] is False
    assert resultat["depots_supports_identiques"] is True
