"""Compare les G-code de rejeux archivés à partir de reçus locaux."""

import hashlib
import json
import math
import os
import re
import stat
from pathlib import Path
from zipfile import BadZipFile

from benchab.archives_3mf import Archive3MF
from benchab.chemins import atelier_prive, sans_lien
from benchab.controles.gcode_interpreter import Interpreter
from benchab.gcode.lecture import plaques_gcode_archive
from benchab.qualite.statuts import code_statut

_SHA = re.compile(r"[0-9a-f]{64}\Z")
_DATE_ASN = re.compile(
    rb"(; generated by AnycubicSlicerNext [0-9]+(?:\.[0-9]+){1,3} on )"
    rb"[0-9]{4}-[0-9]{2}-[0-9]{2} at [0-9]{2}:[0-9]{2}:[0-9]{2}(\r?\n?)"
)
_DEBUT_ENTETE = b"; HEADER_BLOCK_START"
_FIN_ENTETE = b"; HEADER_BLOCK_END"
_ROLES = ("support", "support interface", "support transition")
_MAX_RECU = 2 * 1024**2
_MAX_LIGNE = 1024**2
_MAX_LIGNES = 5_000_000


def _objet_unique(paires):
    """Refuse une clé JSON répétée avant toute interprétation du reçu."""
    resultat = {}
    for cle, valeur in paires:
        if cle in resultat:
            raise ValueError("Clé de reçu JSON dupliquée : " + cle)
        resultat[cle] = valeur
    return resultat


def _signature(info):
    """Identifie un fichier par inode et état observable, en octets et ns."""
    return info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns


def _sha(valeur):
    """Vérifie le format SHA-256, sans interpréter un champ vide comme une preuve."""
    if not isinstance(valeur, str) or not _SHA.fullmatch(valeur):
        raise ValueError("Empreinte SHA-256 requise dans le reçu.")
    return valeur


def _lire_recu(prive, chemin):
    """Lit et hache le même reçu ordinaire, au plus 2 Mio, sans suivre de lien."""
    fichier = sans_lien(Path(chemin).expanduser().absolute(), racine=prive, strict=True)
    with os.fdopen(os.open(fichier, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK), "rb") as flux:
        avant = os.fstat(flux.fileno())
        if not stat.S_ISREG(avant.st_mode) or avant.st_size > _MAX_RECU:
            raise ValueError("Reçu non régulier ou supérieur au budget de 2 Mio.")
        contenu = flux.read(_MAX_RECU + 1)
        if len(contenu) != avant.st_size or not (
            _signature(avant) == _signature(os.fstat(flux.fileno())) == _signature(fichier.lstat())
        ):
            raise ValueError("Reçu modifié pendant sa lecture.")
    r = json.loads(contenu.decode("utf-8"), object_pairs_hook=_objet_unique)
    if not isinstance(r, dict):
        raise ValueError("Objet JSON de reçu requis.")
    publication, validation = r.get("publication_sortie"), r.get("validation_sortie")
    if (
        type(r.get("code")) is not int or r["code"] != 0
        or type(r.get("code_processus")) is not int or r["code_processus"] != 0
        or not isinstance(validation, dict) or validation.get("statut") != "PASS"
        or not isinstance(publication, dict) or publication.get("statut") != "PASS"
    ):
        raise ValueError("Le reçu ne décrit pas une sortie publiée et validée.")
    destination = r.get("destination_finale")
    if (
        not isinstance(destination, str)
        or not Path(destination).is_absolute()
        or Path(destination).suffix.lower() != ".3mf"
        or publication.get("chemin") != destination
    ):
        raise ValueError("La publication du reçu n’identifie pas une sortie absolue unique.")
    sortie = sans_lien(Path(destination), racine=prive, strict=True)
    plan = r.get("plan_matrices_origine")
    binaire = plan.get("binaire") if isinstance(plan, dict) else None
    sha_binaire = _sha(binaire["sha256"]) if isinstance(binaire, dict) and "sha256" in binaire else None
    return {
        "recu": fichier, "recu_sha256": hashlib.sha256(contenu).hexdigest(),
        "signature": _signature(avant), "sortie": sortie,
        "source_sha256": _sha(r.get("source_sha256")), "entree_sha256": _sha(r.get("entree_sha256")),
        "sortie_sha256": _sha(r.get("sortie_sha256")), "binaire_sha256": sha_binaire,
    }


def _mesurer(recu, plaque):
    """Hache le G-code exact en flux et mesure les dépôts de support, longueurs en mm."""
    sortie = recu["sortie"]
    signature = _signature(sortie.lstat())
    with Archive3MF(sortie) as archive:
        if archive.sha256() != recu["sortie_sha256"]:
            raise ValueError("Le 3MF publié ne correspond pas au SHA-256 du reçu.")
        membres = dict(plaques_gcode_archive(archive))
        if plaque not in membres:
            raise ValueError("Plaque demandée absente du 3MF publié.")
        membre = membres[plaque]
        brut, strict, normalise, depots = (hashlib.sha256() for _ in range(4))
        analyse = Interpreter(error_limit=32)
        mesures = {role: {"segments": 0, "longueur_mm": 0.0} for role in _ROLES}
        lignes = 0
        date = entete = fin_entete = False
        with archive.ouvrir_flux(membre) as flux:
            while ligne := flux.readline(_MAX_LIGNE + 1):
                lignes += 1
                if lignes > _MAX_LIGNES or len(ligne) > _MAX_LIGNE:
                    raise ValueError("Budget de lecture G-code dépassé.")
                brut.update(ligne)
                marqueur = ligne.rstrip(b"\r\n")
                if lignes == 1:
                    entete = marqueur == _DEBUT_ENTETE
                elif 2 < lignes <= 32 and entete and not fin_entete:
                    if marqueur == _FIN_ENTETE:
                        fin_entete = True
                    elif marqueur and not marqueur.startswith(b";"):
                        entete = False
                # ASN place cette ligne en deuxième position dans un bloc
                # complet. Un commentaire isolé ne constitue pas une preuve.
                match = _DATE_ASN.fullmatch(ligne) if lignes == 2 and entete else None
                cadre_original = b"\0" + len(ligne).to_bytes(4, "big") + ligne
                strict.update(cadre_original)
                if match is None:
                    normalise.update(cadre_original)
                else:
                    # Le marqueur interne ne peut pas se confondre avec
                    # un commentaire littéral dont le texte a été modifié.
                    charge = match[1] + match[2]
                    normalise.update(b"\1" + len(charge).to_bytes(4, "big") + charge)
                    date = True
                mouvement = analyse.feed_line(ligne.decode("utf-8"))
                if not mouvement or mouvement.get("deposited_length", 0) <= 0:
                    continue
                role = mouvement.get("type")
                role = role.strip().lower() if isinstance(role, str) else ""
                if role not in mesures:
                    continue
                longueur = mouvement["deposited_length"]
                if not math.isfinite(longueur):
                    raise ValueError("Longueur de dépôt non finie.")
                mesures[role]["segments"] += 1
                mesures[role]["longueur_mm"] += longueur
                trajet = [
                    role, mouvement["op"], mouvement["deposition_start"], mouvement["end"],
                    mouvement["deposited"], mouvement.get("arc_g17"),
                ]
                depots.update(json.dumps(trajet, allow_nan=False, separators=(",", ":")).encode() + b"\n")
        archive.verifier_source(sortie)
        if _signature(sortie.lstat()) != signature:
            raise ValueError("Le 3MF de sortie a changé pendant la comparaison.")
        if analyse.errors:
            raise ValueError("Interprétation G-code incomplète : " + analyse.errors[0][:500])
        if not any(m["segments"] for m in mesures.values()):
            raise ValueError("Aucun dépôt de support attribué sur la plaque.")
    date = date and fin_entete
    for mesure in mesures.values():
        mesure["longueur_mm"] = round(mesure["longueur_mm"], 3)
    return {
        "recu_sha256": recu["recu_sha256"], "sortie_sha256": recu["sortie_sha256"], "membre": membre,
        "gcode_sha256": brut.hexdigest(), "gcode_hors_date_sha256": (normalise if date else strict).hexdigest(),
        "date_asn_normalisee": date, "depots_supports_sha256": depots.hexdigest(), "supports": mesures,
        "lignes": lignes,
    }, signature


def comparer(prive, recus, *, plaque):
    """Compare deux ou trois reçus distincts et une plaque explicite (sans unité).

    PASS : G-code identique hors date ASN ; WARN : écart conservé ;
    NON VÉRIFIÉ : reçus non appariés ou mesure incomplète. Les longueurs
    de dépôt sont en mm. Les reçus déclarent des empreintes, sans authentifier
    une exécution. Aucune écriture, commande machine ni preuve physique.
    """
    resultat = {
        "schema": 1, "plaque": plaque, "statut": "NON VÉRIFIÉ", "code": 2,
        "gcode_brut_identique": None, "gcode_hors_date_identique": None,
        "depots_supports_identiques": None, "mesures_supports_identiques": None,
        "identite_binaire": {"statut": "NON VÉRIFIÉ", "sha256": None}, "rejeux": [],
        "validation_physique": False,
        "limite": "Comparaison de fichiers ; les reçus ne certifient pas les exécutions.",
    }
    try:
        if type(plaque) is not int or plaque < 1:
            raise ValueError("Numéro de plaque positif et explicite requis.")
        if not isinstance(recus, (list, tuple)) or not 2 <= len(recus) <= 3:
            raise ValueError("Deux ou trois reçus de rejeu sont requis.")
        atelier = atelier_prive(prive)
        lectures = [_lire_recu(atelier, recu) for recu in recus]
        if len({r["signature"][:2] for r in lectures}) != len(lectures) or len({
            r["sortie"] for r in lectures
        }) != len(lectures):
            raise ValueError("Les reçus et leurs chemins de sortie doivent être distincts.")
        for champ in ("source_sha256", "entree_sha256"):
            if len({r[champ] for r in lectures}) != 1:
                raise ValueError(f"Empreintes de rejeu non appariées : {champ}.")
            resultat[champ] = lectures[0][champ]
        moteurs = {r["binaire_sha256"] for r in lectures} - {None}
        if len(moteurs) > 1:
            raise ValueError("Les reçus déclarent des binaires différents.")
        if moteurs and all(r["binaire_sha256"] for r in lectures):
            resultat["identite_binaire"] = {"statut": "DÉCLARÉE DANS LES REÇUS", "sha256": moteurs.pop()}
        mesures, signatures = zip(*(_mesurer(r, plaque) for r in lectures), strict=True)
        if len({s[:2] for s in signatures}) != len(lectures):
            raise ValueError("Les sorties ne désignent pas des fichiers distincts.")
        for r, signature in zip(lectures, signatures, strict=True):
            if _signature(r["recu"].lstat()) != r["signature"] or _signature(r["sortie"].lstat()) != signature:
                raise ValueError("Un reçu ou un 3MF a changé pendant la comparaison.")
    except (OSError, ValueError, BadZipFile, TypeError, RecursionError) as erreur:
        return {**resultat, "raison": str(erreur)}
    hors_date = len({m["gcode_hors_date_sha256"] for m in mesures}) == 1
    statut = "PASS" if hors_date else "WARN"
    return {
        **resultat, "statut": statut, "code": code_statut(statut), "rejeux": list(mesures),
        "gcode_brut_identique": len({m["gcode_sha256"] for m in mesures}) == 1,
        "gcode_hors_date_identique": hors_date,
        "depots_supports_identiques": len({m["depots_supports_sha256"] for m in mesures}) == 1,
        "mesures_supports_identiques": all(m["supports"] == mesures[0]["supports"] for m in mesures),
    }

